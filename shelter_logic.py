import math

# =========================
# 設定値
# =========================

SUGGEST_DISTANCE_KM = 1.0

CONGESTION_BUSY = 0.6
CONGESTION_FULL = 0.9

MAX_SUGGESTIONS = 3

EARTH_RADIUS_KM = 6371.0088


# =========================
# 距離計算
# =========================

def haversine_km(lat1, lng1, lat2, lng2):

    p1 = math.radians(lat1)
    p2 = math.radians(lat2)

    dp = p2 - p1
    dl = math.radians(lng2 - lng1)

    a = (
        math.sin(dp / 2) ** 2
        + math.cos(p1)
        * math.cos(p2)
        * math.sin(dl / 2) ** 2
    )

    return 2 * EARTH_RADIUS_KM * math.asin(math.sqrt(a))


# =========================
# 混雑率計算
# =========================

def calculate_congestion(current_people, capacity):

    if capacity <= 0:
        return None, "不明"

    rate = current_people / capacity

    if rate >= CONGESTION_FULL:
        return rate, "満員に近い"

    if rate >= CONGESTION_BUSY:
        return rate, "やや混雑"

    return rate, "余裕あり"


# =========================
# 残り収容人数計算
# =========================

def calculate_remaining_capacity(
    current_people,
    capacity
):

    return max(
        capacity - current_people,
        0
    )


# =========================
# スコア計算
# =========================

def calculate_recommendation_scores(
    candidates
):

    if not candidates:
        return []

    max_distance = max(
        c["distance_km"]
        for c in candidates
    )

    max_remaining = max(
        c["remaining_capacity"]
        for c in candidates
    )

    if max_distance <= 0:
        max_distance = 1

    if max_remaining <= 0:
        max_remaining = 1

    for c in candidates:

        # 距離正規化
        Di = (
            c["distance_km"]
            / max_distance
        )

        # 収容余裕度
        Ai = (
            c["remaining_capacity"]
            / max_remaining
        )

        Ci = c["congestion_rate"]

        score = (
            0.5 * (1 - Di)
            + 0.3 * Ai
            + 0.2 * (1 - Ci)
        )

        c["score"] = round(score, 3)

    candidates.sort(
        key=lambda x: x["score"],
        reverse=True
    )

    return candidates


# =========================
# 避難所推薦
# =========================

def suggest_shelters(
    current_lat,
    current_lng,
    designated_id,
    shelters,
    status_map
):

    entries = []

    for shelter in shelters:

        shelter_id = shelter["common_id"]

        if shelter_id not in status_map:
            continue

        status = status_map[shelter_id]

        distance = haversine_km(
            current_lat,
            current_lng,
            shelter["lat"],
            shelter["lng"]
        )

        congestion_rate, congestion_label = (
            calculate_congestion(
                status["current_people"],
                status["capacity"]
            )
        )

        remaining = calculate_remaining_capacity(
            status["current_people"],
            status["capacity"]
        )

        entries.append({
            "common_id": shelter_id,
            "name": shelter["name"],
            "distance_km": round(distance, 3),

            "congestion_rate":
                round(congestion_rate, 2),

            "congestion":
                congestion_label,

            "remaining_capacity":
                remaining
        })

    designated = next(
        (
            s for s in entries
            if str(s["common_id"])
            == str(designated_id)
        ),
        None
    )

    if designated is None:
        raise ValueError(
            "指定避難所が存在しません"
        )

    distance = designated["distance_km"]

    # 0～500m
    if distance <= 0.5:

        return {
            "mode":
                "designated_only",

            "designated":
                designated,

            "message":
                "指定避難所へ避難してください"
        }

    # 500m～1000m
    if distance <= SUGGEST_DISTANCE_KM:

        candidates = [
            e for e in entries
            if e["common_id"]
            != designated["common_id"]
        ]

        calculate_recommendation_scores(
            candidates
        )

        return {
            "mode":
                "show_both",

            "designated":
                designated,

            "candidates":
                candidates[:MAX_SUGGESTIONS]
        }

    # 1000m以上
    candidates = [
        e for e in entries
        if e["common_id"]
        != designated["common_id"]
        and e["congestion"]
        != "満員に近い"
    ]

    candidates = (
        calculate_recommendation_scores(
            candidates
        )
    )

    return {
        "mode":
            "recommend",

        "designated":
            designated,

        "candidates":
            candidates[:MAX_SUGGESTIONS],

        "message":
            "近隣避難所を推薦します"
    }