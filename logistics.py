def calculate_supply_priority(status):

    people = status.get("current_people", 0)

    water_stock = status.get("supplies_water", 0)
    food_stock = status.get("supplies_food", 0)
    blanket_stock = status.get("supplies_blanket", 0)

    capacity = status.get("capacity", 0)

    if people <= 0:
        return None

    # 必要量
    water_required = people * 3
    food_required = people * 3
    blanket_required = people

    # 不足率
    water_lack = max(
        0,
        (water_required - water_stock)
        / water_required
    )

    food_lack = max(
        0,
        (food_required - food_stock)
        / food_required
    )

    blanket_lack = max(
        0,
        (blanket_required - blanket_stock)
        / blanket_required
    )

    # 物資不足度
    supply_score = (
        0.5 * water_lack +
        0.3 * food_lack +
        0.2 * blanket_lack
    )

    # 混雑率
    congestion = (
        people / capacity
        if capacity > 0
        else 0
    )

    # 配送優先度
    priority = (
        0.6 * supply_score +
        0.4 * congestion
    )

    return {
        "water_lack": round(water_lack, 3),
        "food_lack": round(food_lack, 3),
        "blanket_lack": round(blanket_lack, 3),
        "supply_score": round(supply_score, 3),
        "congestion": round(congestion, 3),
        "priority": round(priority, 3)
    }